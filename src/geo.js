/** 经纬度 → 逻辑地图坐标 */
export const projX = lon => (lon - WORLD.lonMin) * WORLD.K;
export const projY = lat => (WORLD.latMax - lat) * WORLD.K;
export const project = (lon, lat) => ({ x: projX(lon), y: projY(lat) });
/** 逻辑地图坐标 → 经纬度 */
export const unprojLon = x => x / WORLD.K + WORLD.lonMin;
export const unprojLat = y => WORLD.latMax - y / WORLD.K;

/** 两点真实大圆距离（公里），用于航海志显示 */
export function greatCircleKm(lon1, lat1, lon2, lat2) {
  const R = 6371, rad = Math.PI / 180;
  const dLat = (lat2 - lat1) * rad, dLon = (lon2 - lon1) * rad;
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin(dLon / 2) ** 2;
  return Math.round(2 * R * Math.asin(Math.min(1, Math.sqrt(a))));
}

